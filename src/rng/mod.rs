//! Pseudo-random number generation utilities.
//!
//! This module provides the [`PRNG`] interface and a [`Xoshiro256`] generator.
//! `Xoshiro256` is a fast, non-cryptographic generator intended for simulations,
//! randomized algorithms, and test data. It must not be used for secrets,
//! passwords, or security tokens.
mod xoshiro256;

use std::f64;

use wide::{f64x2, f64x4, u64x2, u64x4};

use crate::Error::EmptySlicePick;
use crate::Result;
pub use xoshiro256::Xoshiro256;

/// Common operations provided by a pseudo-random number generator.
pub trait PRNG {
    /// Returns a random `u64` generated by the underlying generator.
    ///
    /// # Returns
    ///
    /// A pseudo-random `u64` value.
    fn random(&mut self) -> u64;

    /// Returns a random floating-point value derived from [`Self::random`].
    ///
    /// The result is approximately in the interval `[0.0, 1.0]`. This method
    /// is intended for basic use; callers requiring a particular distribution
    /// should apply an appropriate transformation.
    ///
    /// # Returns
    ///
    /// A pseudo-random value approximately in `[0.0, 1.0]`.
    #[inline]
    fn percentage(&mut self) -> f64 {
        (self.random() as f64) / (u64::MAX as f64)
    }

    /// Generates a uniformly distributed index in `0..upper_limit`.
    ///
    /// # Arguments
    ///
    /// * `upper_limit` - Exclusive upper bound of the generated index.
    ///
    /// # Panics
    ///
    /// Panics if `upper_limit` is zero.
    fn usize(&mut self, upper_limit: usize) -> usize {
        assert!(upper_limit > 0);

        let upper_limit = upper_limit as u64;
        let limit = u64::MAX - (u64::MAX % upper_limit);

        loop {
            let value = self.random();

            if value < limit {
                return (value % upper_limit) as usize;
            }
        }
    }

    /// Returns a reference to a uniformly selected element of `data`.
    ///
    /// # Arguments
    ///
    /// * `data` - Non-empty slice from which to select an element.
    ///
    /// # Errors
    ///
    /// Returns [`crate::Error::EmptySlicePick`] if `data` is empty.
    fn element<'a, T>(&mut self, data: &'a [T]) -> Result<&'a T> {
        if data.is_empty() {
            Err(EmptySlicePick)
        } else {
            Ok(&data[self.usize(data.len())])
        }
    }

    /// Returns a mutable reference to a uniformly selected element of `data`.
    ///
    /// # Arguments
    ///
    /// * `data` - Non-empty slice from which to select an element.
    ///
    /// # Errors
    ///
    /// Returns [`crate::Error::EmptySlicePick`] if `data` is empty.
    fn element_mut<'a, T>(&mut self, data: &'a mut [T]) -> Result<&'a mut T> {
        if data.is_empty() {
            Err(EmptySlicePick)
        } else {
            Ok(&mut data[self.usize(data.len())])
        }
    }

    /// Shuffles `data` in place using this generator.
    ///
    /// # Arguments
    ///
    /// * `data` - Slice whose elements will be rearranged in place.
    ///
    /// # Returns
    ///
    /// Returns nothing. The supplied slice is modified directly.
    fn shuffle<T>(&mut self, data: &mut [T]) {
        if data.is_empty() {
            return;
        }
        let length = data.len();
        for i in 0..length - 1 {
            let r = self.usize(length) + i;
            data.swap(i, r);
        }
    }
}

/// Probability distributions built on top of [`PRNG`].
pub trait Distributions: PRNG {
    /// Returns a uniformly distributed `f64` in the open interval `(0, 1)`.
    ///
    /// The value is built from 52 random bits and scaled into the open interval
    /// `(0, 1)`. The open interval is useful for transformations that apply
    /// `ln`, since the result can never be exactly zero or one.
    ///
    /// # Returns
    ///
    /// A uniformly distributed value in `(0, 1)`.
    fn uniform(&mut self) -> f64 {
        let bits = self.random() >> 12;
        (bits as f64 + 1.0) / ((1u64 << 52) + 1) as f64
    }

    /// Returns a standard-normal value with mean `0` and standard deviation
    /// `1`, using ratio-of-uniforms rejection sampling.
    ///
    /// # Returns
    ///
    /// A sample from the standard normal distribution.
    fn normal(&mut self) -> f64 {
        let factor = (2.0 / f64::consts::E).sqrt();
        loop {
            let u = self.uniform();
            let v = (2.0 * self.uniform() - 1.0) * factor;

            if v * v <= -4.0 * u * u * u.ln() {
                return v / u;
            }
        }
    }

    /// Returns `true` with probability `probability` and `false` otherwise.
    ///
    /// # Panics
    ///
    /// Panics if `probability` is outside the inclusive range `0.0..=1.0`.
    ///
    /// # Arguments
    ///
    /// * `probability` - Probability of returning `true`.
    ///
    /// # Returns
    ///
    /// `true` with probability `probability`; otherwise `false`.
    fn bernoulli(&mut self, probability: f64) -> bool {
        assert!((0.0..=1.0).contains(&probability));

        self.uniform() < probability
    }

    /// Returns an exponentially distributed waiting time with the given rate.
    ///
    /// The expected value is `1.0 / rate`.
    ///
    /// # Panics
    ///
    /// Panics if `rate` is not positive.
    ///
    /// # Arguments
    ///
    /// * `rate` - Positive event rate.
    ///
    /// # Returns
    ///
    /// A non-negative exponentially distributed waiting time with mean `1.0 / rate`.
    fn exponential(&mut self, rate: f64) -> f64 {
        assert!(rate > 0.0);
        let u = self.uniform();
        -u.ln() / rate
    }

    /// Returns the number of failures before the first success in independent
    /// Bernoulli trials with the given success probability.
    ///
    /// # Panics
    ///
    /// Panics if `probability` is not in `(0.0, 1.0]`.
    ///
    /// # Arguments
    ///
    /// * `probability` - Success probability of each Bernoulli trial.
    ///
    /// # Returns
    ///
    /// The number of failures before the first success.
    fn geometric(&mut self, probability: f64) -> u64 {
        assert!((0.0..=1.0).contains(&probability));
        assert!(probability > 0.0);

        let u = self.uniform();
        let failure_probability = 1.0 - probability;

        (u.ln() / failure_probability.ln()).floor() as u64
    }

    /// Returns a Poisson-distributed event count with the given expected rate.
    ///
    /// This implementation uses Knuth's product method and is best suited to
    /// small or moderate rates. Its running time grows approximately with
    /// `rate`.
    ///
    /// # Panics
    ///
    /// Panics if `rate` is negative.
    ///
    /// # Arguments
    ///
    /// * `rate` - Non-negative expected event count.
    ///
    /// # Returns
    ///
    /// A Poisson-distributed event count.
    fn poisson(&mut self, rate: f64) -> u64 {
        assert!(rate >= 0.0);

        if rate == 0.0 {
            return 0;
        }

        let limit = (-rate).exp();
        let mut probability = 1.0;
        let mut count = 0;

        loop {
            probability *= self.uniform();

            if probability <= limit {
                return count;
            }

            count += 1;
        }
    }

    /// Returns the number of successes in `trials` independent Bernoulli
    /// trials with the given success probability.
    ///
    /// # Panics
    ///
    /// Panics if `probability` is outside the inclusive range `0.0..=1.0`.
    ///
    /// # Arguments
    ///
    /// * `trials` - Number of independent Bernoulli trials.
    /// * `probability` - Success probability for each trial.
    ///
    /// # Returns
    ///
    /// The number of successful trials.
    fn binomial(&mut self, trials: u64, probability: f64) -> u64 {
        assert!((0.0..=1.0).contains(&probability));

        (0..trials).filter(|_| self.uniform() < probability).count() as u64
    }

    /// Selects an index according to non-negative relative weights.
    ///
    /// # Arguments
    ///
    /// * `weights` - Non-empty slice of finite, non-negative weights.
    ///
    /// # Returns
    ///
    /// An index selected with probability proportional to its weight.
    ///
    /// # Panics
    ///
    /// Panics if `weights` is empty, contains a negative weight, contains a
    /// non-finite value, or has a non-positive total.
    fn categorical(&mut self, weights: &[f64]) -> usize {
        assert!(!weights.is_empty());
        assert!(weights.iter().all(|weight| *weight >= 0.0));

        let total: f64 = weights.iter().sum();
        assert!(total.is_finite() && total > 0.0);

        let target = self.uniform() * total;
        let mut cumulative = 0.0;

        for (index, weight) in weights.iter().enumerate() {
            cumulative += weight;

            if target < cumulative {
                return index;
            }
        }

        // Protects against floating-point rounding.
        weights.len() - 1
    }

    /// Generates a log-normal random value.
    ///
    /// # Arguments
    ///
    /// * `mean` - Mean of the underlying normal distribution.
    /// * `std_dev` - Standard deviation of the underlying normal distribution.
    ///
    /// # Returns
    ///
    /// A positive log-normal sample.
    ///
    /// # Panics
    ///
    /// Panics if `std_dev` is negative.
    fn log_normal(&mut self, mean: f64, std_dev: f64) -> f64 {
        assert!(std_dev >= 0.0);

        (mean + std_dev * self.normal()).exp()
    }

    /// Generates a Gamma-distributed random value.
    ///
    /// # Arguments
    ///
    /// * `shape` - Positive shape parameter.
    /// * `rate` - Positive rate parameter. The scale is `1.0 / rate`.
    ///
    /// # Returns
    ///
    /// A non-negative Gamma-distributed sample.
    ///
    /// # Panics
    ///
    /// Panics if `shape` or `rate` is not positive.
    fn gamma(&mut self, mut shape: f64, rate: f64) -> f64 {
        assert!(shape > 0.0);
        assert!(rate > 0.0);

        let original_shape = shape;
        if original_shape < 1.0 {
            shape += 1.0;
        }

        let d = shape - 1.0 / 3.0;
        let c = 1.0 / (9.0 * d).sqrt();
        let r;

        loop {
            let x = self.normal();
            let v = 1.0 + c * x;

            if v <= 0.0 {
                continue;
            }

            let v = v * v * v;
            let u = self.uniform();

            if u < 1.0 - 0.0331 * x.powi(4) {
                r = d * v / rate;
                break;
            }

            if u.ln() < 0.5 * x * x + d * (1.0 - v + v.ln()) {
                r = d * v / rate;
                break;
            }
        }

        if shape == original_shape {
            r
        } else {
            r * self.uniform().powf(1.0 / original_shape)
        }
    }

    /// Generates a Beta-distributed random value.
    ///
    /// # Arguments
    ///
    /// * `alpha` - Positive first shape parameter.
    /// * `beta` - Positive second shape parameter.
    ///
    /// # Returns
    ///
    /// A Beta-distributed sample in `(0, 1)`.
    ///
    /// # Panics
    ///
    /// Panics if `alpha` or `beta` is not positive.
    fn beta(&mut self, alpha: f64, beta: f64) -> f64 {
        assert!(alpha > 0.0);
        assert!(beta > 0.0);

        let x = self.gamma(alpha, 1.0);
        let y = self.gamma(beta, 1.0);

        x / (x + y)
    }
}

/// SIMD distribution operations using two `f64` lanes.
pub trait DistributionSimd2: Distributions {
    /// Returns two independent uniform samples in `(0, 1)`.
    ///
    /// # Returns
    ///
    /// A two-lane vector containing values in `(0, 1)`.
    fn uniform_2(&mut self) -> f64x2 {
        let bits: u64x2 = u64x2::new([self.random(), self.random()]) >> 12;
        let values = f64x2::new(bits.to_array().map(|value| value as f64));
        (values + 1.0) / f64x2::splat(((1u64 << 52) + 1) as f64)
    }

    /// Returns two independent standard-normal samples.
    ///
    /// # Returns
    ///
    /// A two-lane vector of standard-normal values.
    fn normal_2(&mut self) -> f64x2 {
        let mut out = [0.0; 2];
        let mut pos = 0;
        let factor = f64x2::splat((2.0 / f64::consts::E).sqrt());

        while pos < out.len() {
            let u = self.uniform_2();
            let v = (2.0 * self.uniform_2() - 1.0) * factor;
            let mut remaining = (v * v).simd_le(-4.0 * u * u * u.ln()).to_bitmask();
            let samples = (v / u).to_array();

            while remaining != 0 && pos < out.len() {
                let lane = remaining.trailing_zeros() as usize;
                out[pos] = samples[lane];
                pos += 1;
                remaining &= remaining - 1;
            }
        }

        f64x2::new(out)
    }

    /// Returns two independent exponential samples.
    ///
    /// # Arguments
    ///
    /// * `rate` - Positive event rate.
    ///
    /// # Returns
    ///
    /// A two-lane vector of non-negative waiting times.
    ///
    /// # Panics
    ///
    /// Panics if `rate` is not positive.
    fn exponential_2(&mut self, rate: f64) -> f64x2 {
        assert!(rate > 0.0);
        -self.uniform_2().ln() / f64x2::splat(rate)
    }

    /// Returns two independent geometric samples.
    ///
    /// # Arguments
    ///
    /// * `probability` - Success probability in `(0, 1]`.
    ///
    /// # Returns
    ///
    /// A two-lane vector containing failure counts before the first success.
    ///
    /// # Panics
    ///
    /// Panics if `probability` is not in `(0.0, 1.0]`.
    fn geometric_2(&mut self, probability: f64) -> u64x2 {
        assert!((0.0..=1.0).contains(&probability));
        assert!(probability > 0.0);

        let u = self.uniform_2();
        let failure_probability = f64x2::splat(1.0 - probability);
        u64x2::new(
            (u.ln() / failure_probability.ln())
                .floor()
                .to_array()
                .map(|value| value as u64),
        )
    }
}

/// SIMD distribution operations using four `f64` lanes.
